import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
mkdirSync(new URL('dist/', root), { recursive: true });
const core = readFileSync(new URL('src/core.js', root), 'utf8').replace(/^export /gm, '');
for (const target of ['backend', 'frontend']) {
  const entry = readFileSync(new URL(`src/${target}.js`, root), 'utf8').replace(/^import .* from '\.\/core\.js';\r?\n/gm, '');
  writeFileSync(new URL(`dist/${target}.js`, root), `// Generated by scripts/build.mjs. Edit src/, then rebuild.\n${core}\n${entry}`);
  console.log(`Built ${fileURLToPath(new URL(`dist/${target}.js`, root))}`);
}
